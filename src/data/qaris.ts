/**
 * Returns audio MP3 URL for an ayah from EveryAyah CDN
 */
export function getAyahAudioUrl(reciterSubfolder: string, surah: number, ayah: number): string {
  const sStr = String(surah).padStart(3, '0');
  const aStr = String(ayah).padStart(3, '0');
  return `https://everyayah.com/data/${reciterSubfolder}/${sStr}${aStr}.mp3`;
}

/**
 * Returns prioritized array of audio MP3 URLs (primary EveryAyah CDN + fallback Quran.com CDN)
 */
export function getAyahAudioUrls(qari: Qari, surah: number, ayah: number): string[] {
  const sStr = String(surah).padStart(3, '0');
  const aStr = String(ayah).padStart(3, '0');
  const urls: string[] = [
    `https://everyayah.com/data/${qari.everyAyahSubfolder}/${sStr}${aStr}.mp3`
  ];

  // Quran.com CDN fallbacks
  if (qari.id === 'alafasy') {
    urls.push(`https://verses.quran.com/Alafasy/mp3/${sStr}${aStr}.mp3`);
  } else if (qari.id === 'abdulbasit_mujawwad') {
    urls.push(`https://verses.quran.com/AbdulBaset/Mujawwad/mp3/${sStr}${aStr}.mp3`);
  } else if (qari.id === 'abdulbasit_murattal') {
    urls.push(`https://verses.quran.com/AbdulBaset/Murattal/mp3/${sStr}${aStr}.mp3`);
  } else if (qari.id === 'minshawy') {
    urls.push(`https://verses.quran.com/Minshawi/Murattal/mp3/${sStr}${aStr}.mp3`);
  } else if (qari.id === 'husary') {
    urls.push(`https://verses.quran.com/Husary/mp3/${sStr}${aStr}.mp3`);
  }

  return urls;
}

